def run(raw, out_dir=OUTPUT_DIR, verbose=True):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(RNG_SEED)
    valid = valid_mask(raw)
    if verbose:
        print(f'Valid pixels: {valid.sum()} / {valid.size}')
    processed, edges, G = detect_graph(raw, valid)
    g = pixel_geometry(G)
    if verbose:
        print(f'Edge pixels in graph: {len(g.nodes)}, voting pixels: {int(g.eligible.sum())}')
    stack = vote_stack(g, raw.shape)
    best, best_alpha, cands = candidate_centres(stack, valid)
    if verbose:
        print(f'Candidate peaks: {len(cands)}')
    null = null_maxima(g, valid, raw.shape, rng) if N_NULL > 0 else np.zeros(0)
    if verbose and len(null):
        print(f'Null maxima ({len(null)} rearrangements): median {np.median(null):.2f}, '
              f'95th pct {np.percentile(null, 95):.2f}')

    results, covs, rows, seg_rows, arm_rows, all_chains = [], [], [], [], [], []
    for c0, a0, peak in cands:
        res = refine_centre(G, g, c0.copy(), a0)
        if any(np.hypot(*(res['centre'] - r['centre'])) < MIN_CENTRE_SEP for r in results):
            if verbose:
                print(f'  candidate at ({c0[0]:.0f},{c0[1]:.0f}) converged onto an existing centre; dropped')
            continue
        cov, _ = bootstrap_centre(g, res, rng)
        theta, r, segs, summ = describe(g, res)
        k = len(results)
        results.append(res)
        covs.append(cov)
        rows.append(dict(centre=k, x=res['centre'][0], y=res['centre'][1],
                         sigma_x=np.sqrt(cov[0, 0]), sigma_y=np.sqrt(cov[1, 1]),
                         pitch_deg=res['alpha'], initial_x=c0[0], initial_y=c0[1],
                         initial_pitch_deg=a0, peak_votes=peak,
                         null_p=float((1 + (null >= peak).sum()) / (1 + len(null))) if len(null) else np.nan,
                         peak_over_null95=float(peak / np.percentile(null, 95)) if len(null) else np.nan,
                         status=res['status'], **summ))
        for s in segs:
            seg_rows.append(dict(centre=k, **s))
        chains, _, links = build_arms(G, g, res, valid)
        all_chains.append(chains)
        for n, ch in enumerate(chains):
            arm_rows.append(dict(centre=k, chain=n, segments=' '.join(map(str, ch['segments'])),
                                 **{key: ch[key] for key in ('n_segments', 'winding_deg', 'turns',
                                                             'pitch_deg', 'rms_lnr', 'bridged_fraction',
                                                             'r_min', 'r_max', 'theta_start_deg')}))
        plot_arms(k, processed, g, res, chains, out_dir / f'centre_{k}_arms.png')
        plot_centre(k, processed, g, stack, (c0, a0, peak), res, cov, theta, r, segs, summ,
                    out_dir / f'centre_{k}.png',
                    p_text=f"null p={rows[-1]['null_p']:.3f}, " if len(null) else '')
        if verbose:
            print(f"  centre {k}: ({res['centre'][0]:.1f} +/- {np.sqrt(cov[0, 0]):.1f}, "
                  f"{res['centre'][1]:.1f} +/- {np.sqrt(cov[1, 1]):.1f}) px, "
                  f"pitch {res['alpha']:+.1f} deg, {summ['n_segments']} segments, "
                  f"coverage {summ['angular_coverage']:.0%}, "
                  f"r {summ['r_member_min']:.0f}-{summ['r_member_max']:.0f} px, "
                  f"rms miss {summ['rms_miss_px']:.2f} px, "
                  f"p={rows[-1]['null_p']:.3f} [{res['status']}]")
            for ch in [c for c in chains if c['n_segments'] > 1]:
                print(f"     arm: {ch['n_segments']} segments, winding {ch['winding_deg']:.0f} deg, "
                      f"pitch {ch['pitch_deg']:+.1f} deg, r {ch['r_min']:.0f}-{ch['r_max']:.0f} px, "
                      f"bridged {ch['bridged_fraction']:.0%}")

    plot_overview(processed, g, best, cands, results, covs, out_dir / 'overview.png')
    for name, table in (('centres.csv', rows), ('segments.csv', seg_rows), ('arms.csv', arm_rows)):
        if table:
            with (out_dir / name).open('w', newline='') as f:
                w = csv.DictWriter(f, fieldnames=list(table[0]))
                w.writeheader()
                w.writerows(table)
    np.savez_compressed(out_dir / 'swirl_centres.npz', processed=processed, valid=valid,
                        edges=edges, pixel_xy=g.Ps, normal=g.Nc, kappa=g.kappa,
                        weight=g.weight, alphas_deg=ALPHAS_DEG, vote_stack=stack,
                        null_maxima=null,
                        centres=np.array([r['centre'] for r in results]).reshape(-1, 2),
                        pitch_deg=np.array([r['alpha'] for r in results]),
                        member_labels=np.array([r['labels'] for r in results]).reshape(len(results), -1))
    return dict(results=results, covs=covs, centres_table=rows, segments_table=seg_rows,
                geometry=g, stack=stack, candidates=cands, null_maxima=null,
                arms_table=arm_rows, chains=all_chains, G=G, processed=processed,
                valid=valid)


def main():
    raw = tracker.load_frame(FITS_FILE, FRAME_INDEX)
    run(raw)
    print('Saved:', OUTPUT_DIR)


if __name__ == '__main__':
    main()
