def _padded_lines(arr):
    """Flag rows of arr that are constant or exact copies of a neighbour row,
    keeping only runs of length >= PAD_MIN_RUN."""
    n = arr.shape[0]
    flag = np.zeros(n, bool)
    for i in range(n):
        row = arr[i]
        fin = np.isfinite(row)
        if not fin.any() or np.ptp(row[fin]) == 0:
            flag[i] = True
        if i > 0 and np.array_equal(row, arr[i - 1], equal_nan=True):
            flag[i] = flag[i - 1] = True
    out = np.zeros(n, bool)
    i = 0
    while i < n:
        if flag[i]:
            j = i
            while j < n and flag[j]:
                j += 1
            if j - i >= PAD_MIN_RUN:
                out[i:j] = True
            i = j
        else:
            i += 1
    return out


def valid_mask(raw):
    valid = np.isfinite(raw)
    if ZERO_IS_INVALID:
        valid &= raw != 0
    if AUTO_MASK_PADDING:
        valid[_padded_lines(raw), :] = False
        valid[:, _padded_lines(raw.T)] = False
    if MANUAL_VALID_BOX is not None:
        y0, y1, x0, x1 = MANUAL_VALID_BOX
        box = np.zeros_like(valid)
        box[y0:y1, x0:x1] = True
        valid &= box
    if not valid.any():
        raise ValueError('No valid pixels after masking.')
    return valid


def detect_graph(raw, valid):
    """Tracker preprocessing + Canny + graph, restricted to the valid region."""
    filled = np.asarray(raw, float).copy()
    filled[~valid] = np.median(filled[valid])
    processed = tracker.preprocess(filled)
    inner = binary_erosion(valid, iterations=MASK_MARGIN, border_value=0)
    edges = canny(processed, sigma=tracker.CANNY_SIGMA,
                  low_threshold=tracker.CANNY_LOW,
                  high_threshold=tracker.CANNY_HIGH, mask=inner)
    edges &= inner
    return processed, edges, tracker.build_graph(edges)


