"""Locate chromospheric swirl centres via curvature-weighted normal voting.

Place beside swirl_tracer.py and run:
    python swirl_centre_voting.py

Method
------
Every pixel on a curved edge casts a vote along a ray oriented towards its
concave side. For concentric rings or logarithmic spiral arms, rays rotated by
the pitch angle alpha converge on the vortex rotation centre.

Pipeline
--------
1. Mask padded or invalid boundary regions and build the Canny m-adjacency graph.
2. Estimate smoothed graph coordinates, PCA tangents, quadratic curvature, and
   concave normals. Vote weight is coherence * curvature confidence, suppressing
   straight segments and multi-branch junctions.
3. Pitch-angle voting: for trial pitch angles alpha, rotate normals by alpha
   and accumulate rays between R_MIN and R_MAX.
4. Iterative refinement per candidate peak:
   - Assign member pixels where |psi_i - alpha| <= PSI_TOL and R_MIN <= r <= R_MAX.
   - Apply a graph-majority filter over MEMBER_HOPS and discard short fragments.
   - Update the centre via weighted least-squares line intersection and update
     alpha via the weighted median of member pointing angles until convergence.
5. Estimate centre uncertainty by bootstrapping over member segments.
6. Evaluate peak significance against null maps generated by randomly rotating
   and translating the observed edge fragments across the valid field of view.
7. Fit local log-spiral models to member segments and link compatible segments
   into candidate spiral arms.

Sign convention
---------------
Coordinates are x = column, y = row (displayed with origin='lower').
Pitch alpha > 0 indicates radius increasing counter-clockwise; alpha < 0
indicates radius increasing clockwise; alpha ~ 0 corresponds to circular rings.
"""
