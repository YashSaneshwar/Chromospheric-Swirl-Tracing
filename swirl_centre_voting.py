# Voting
# -----------------------------------------------------------------------------
def vote_map(P, D, W, shape):
    s = np.arange(R_MIN, R_MAX + RAY_STEP / 2, RAY_STEP)
    H = np.zeros(shape[0] * shape[1])
    use = W > 0
    P, D, W = P[use], D[use], W[use]
    for k in range(0, len(P), VOTE_CHUNK):
        p, d, w = P[k:k + VOTE_CHUNK], D[k:k + VOTE_CHUNK], W[k:k + VOTE_CHUNK]
        xi = np.rint(p[:, None, 0] + s[None, :] * d[:, None, 0]).astype(int)
        yi = np.rint(p[:, None, 1] + s[None, :] * d[:, None, 1]).astype(int)
        ok = (xi >= 0) & (xi < shape[1]) & (yi >= 0) & (yi < shape[0])
        ww = np.broadcast_to(w[:, None], xi.shape)[ok]
        H += np.bincount(yi[ok] * shape[1] + xi[ok], weights=ww, minlength=H.size)
    return gaussian_filter(H.reshape(shape) * RAY_STEP, VOTE_BLUR)


def vote_stack(g, shape):
    return np.array([vote_map(g.Ps, rotate(g.Nc, a), g.weight, shape) for a in ALPHAS_DEG])


def candidate_centres(stack, valid):
    best = stack.max(0)
    best_alpha = ALPHAS_DEG[stack.argmax(0)]
    masked = np.where(valid, best, 0.0)
    peaks = peak_local_max(masked, min_distance=MIN_CENTRE_SEP,
                           threshold_rel=PEAK_THRESHOLD_REL,
                           num_peaks=N_CENTRES, exclude_border=False)
    return best, best_alpha, [(np.array([c, r], float), float(best_alpha[r, c]),
                               float(best[r, c])) for r, c in peaks]


def null_maxima(g, valid, shape, rng):
    """Image-wide maximum vote (over pitch) for randomly re-arranged fragments."""
    vy, vx = np.nonzero(valid)
    comps = np.unique(g.component[g.eligible])
    maxima = []
    for _ in range(N_NULL):
        Ps, Nc = g.Ps.copy(), g.Nc.copy()
        for k in comps:
            sel = g.component == k
            phi = rng.uniform(-180, 180)
            centroid = Ps[sel].mean(0)
            j = rng.integers(len(vx))
            Ps[sel] = rotate(Ps[sel] - centroid, phi) + np.array([vx[j], vy[j]], float)
            Nc[sel] = rotate(Nc[sel], phi)
        best = max(np.where(valid, vote_map(Ps, rotate(Nc, a), g.weight, shape), 0).max()
                   for a in ALPHAS_DEG)
        maxima.append(best)
    return np.array(maxima)


# -----------------------------------------------------------------------------
# Membership and refinement
# -----------------------------------------------------------------------------
def membership(G, g, centre, alpha):
    v = centre - g.Ps
    dist = np.hypot(v[:, 0], v[:, 1])
    psi = signed_angle(g.Nc, v)
    in_range = (dist >= R_MIN) & (dist <= R_MAX)
    raw = g.eligible & in_range & (np.abs(wrap(psi - alpha)) <= PSI_TOL_DEG)
    n_elig = g.hood @ g.eligible.astype(float)
    n_hit = g.hood @ raw.astype(float)
    score = np.divide(n_hit, n_elig, out=np.zeros_like(n_hit), where=n_elig >= 3)
    member = (score >= 0.5) & in_range
    labels = -np.ones(len(g.nodes), int)
    sub = G.subgraph([g.nodes[i] for i in np.nonzero(member)[0]])
    index = {node: i for i, node in enumerate(g.nodes)}
    k = 0
    for comp in sorted(nx.connected_components(sub), key=len, reverse=True):
        if len(comp) >= MIN_SEGMENT_PIXELS:
            labels[[index[n] for n in comp]] = k
            k += 1
    return labels, psi, dist


def lsq_centre(P, D, W):
    """Weighted least-squares intersection of lines (P_i, direction D_i)."""
    if len(P) < 3:
        return None
    proj = np.eye(2)[None] - D[:, :, None] * D[:, None, :]
    M = np.einsum('n,nij->ij', W, proj)
    b = np.einsum('n,nij,nj->i', W, proj, P)
    ev = np.linalg.eigvalsh(M)
    if ev[0] < 1e-3 * ev[1]:
        return None
    return np.linalg.solve(M, b)


def weighted_median(x, w):
    order = np.argsort(x)
    cw = np.cumsum(w[order])
    return float(x[order][np.searchsorted(cw, 0.5 * cw[-1])])


def refine_centre(G, g, centre, alpha):
    history = [(centre.copy(), alpha)]
    status = 'max_iter'
    for _ in range(MAX_ITER):
        labels, psi, dist = membership(G, g, centre, alpha)
        use = (labels >= 0) & g.eligible
        if use.sum() < MIN_SEGMENT_PIXELS:
            status = 'too_few_members'
            break
        D = rotate(g.Nc[use], alpha)
        new_c = lsq_centre(g.Ps[use], D, g.weight[use])
        if new_c is None:
            status = 'ill_conditioned'
            break
        new_a = float(np.clip(weighted_median(psi[use], g.weight[use]),
                              ALPHAS_DEG.min(), ALPHAS_DEG.max()))
        shift = np.hypot(*(new_c - centre))
        centre, alpha = new_c, new_a
        history.append((centre.copy(), alpha))
        if shift < 0.05 and abs(new_a - history[-2][1]) < 0.1:
            status = 'converged'
            break
    labels, psi, dist = membership(G, g, centre, alpha)
    return dict(centre=centre, alpha=alpha, labels=labels, psi=psi,
                dist=dist, status=status, history=history)


def bootstrap_centre(g, res, rng):
    labels, alpha = res['labels'], res['alpha']
    use = (labels >= 0) & g.eligible
    segs = np.unique(labels[use])
    if len(segs) < 2:
        return np.full((2, 2), np.nan), np.zeros((0, 2))
    P, W = g.Ps[use], g.weight[use]
    D = rotate(g.Nc[use], alpha)
    lab = labels[use]
    draws = []
    for _ in range(N_BOOT):
        pick = rng.choice(segs, size=len(segs), replace=True)
        mult = np.bincount(np.searchsorted(segs, pick), minlength=len(segs))
        w = W * mult[np.searchsorted(segs, lab)]
        keep = w > 0
        c = lsq_centre(P[keep], D[keep], w[keep])
        if c is not None:
            draws.append(c)
    draws = np.array(draws)
    cov = np.cov(draws.T) if len(draws) > 2 else np.full((2, 2), np.nan)
    return cov, draws


def describe(g, res):
    c, labels = res['centre'], res['labels']
    v = g.Ps - c
    theta = np.degrees(np.arctan2(v[:, 1], v[:, 0]))
    r = np.hypot(v[:, 0], v[:, 1])
    d = rotate(g.Nc, res['alpha'])
    miss = np.abs(d[:, 0] * v[:, 1] - d[:, 1] * v[:, 0])
    member = labels >= 0
    segments = []
    for k in np.unique(labels[member]):
        sel = labels == k
        ev = sel & g.eligible
        th = np.sort(theta[sel])
        gaps = np.diff(np.r_[th, th[0] + 360])
        segments.append(dict(segment=int(k), n_pixels=int(sel.sum()),
                             r_mean=float(r[sel].mean()), r_min=float(r[sel].min()),
                             r_max=float(r[sel].max()),
                             theta_span_deg=float(360 - gaps.max()),
                             pitch_deg=float(np.median(res['psi'][ev])) if ev.any() else np.nan,
                             median_miss_px=float(np.median(miss[ev])) if ev.any() else np.nan))
    covered = np.unique(((theta[member] + 180) // 10).astype(int)) if member.any() else []
    ev = member & g.eligible
    summary = dict(n_member_pixels=int(member.sum()), n_segments=len(segments),
                   angular_coverage=len(covered) / 36.0,
                   r_member_min=float(r[member].min()) if member.any() else np.nan,
                   r_member_max=float(r[member].max()) if member.any() else np.nan,
                   rms_miss_px=float(np.sqrt(np.average(miss[ev] ** 2, weights=g.weight[ev])))
                   if ev.any() else np.nan)
    return theta, r, segments, summary


