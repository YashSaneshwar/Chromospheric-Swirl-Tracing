def _limits(ax, shape):
    ax.set_xlim(-0.5, shape[1] - 0.5)
    ax.set_ylim(-0.5, shape[0] - 0.5)
    ax.set_aspect('equal', adjustable='box')


def _ellipse(ax, c, cov, **kw):
    if not np.all(np.isfinite(cov)):
        return
    vals, vecs = np.linalg.eigh(cov)
    ang = np.degrees(np.arctan2(vecs[1, 1], vecs[0, 1]))
    ax.add_patch(Ellipse(c, 4 * np.sqrt(vals[1]), 4 * np.sqrt(vals[0]),
                         angle=ang, fill=False, **kw))


def plot_centre(k, processed, g, stack, cand, res, cov, theta, r, segs, summ, out, p_text=''):
    c, alpha, labels = res['centre'], res['alpha'], res['labels']
    member = labels >= 0
    cmap = plt.get_cmap('tab20')
    fig, axs = plt.subplots(1, 3, figsize=(18, 6), constrained_layout=True)
    fig.suptitle(f'Centre {k}: ({c[0]:.1f}, {c[1]:.1f}) px, pitch {alpha:+.1f} deg, '
                 f'{summ["n_segments"]} segments, coverage {summ["angular_coverage"]:.0%}, '
                 f'{p_text}status={res["status"]}', fontsize=14, weight='bold')

    # --- Subplot 1: Member segments ---
    ax = axs[0]
    ax.imshow(processed, cmap='gray', origin='lower', vmin=0, vmax=1)
    ax.scatter(g.Ps[:, 0], g.Ps[:, 1], s=1, c='0.55', alpha=0.6, lw=0)
    for s in np.unique(labels[member]):
        sel = labels == s
        ax.scatter(g.Ps[sel, 0], g.Ps[sel, 1], s=4, color=cmap(s % 20), lw=0)
    ax.plot(*c, '+', color='red', ms=14, mew=2)
    _ellipse(ax, c, cov, color='red', lw=1.5)
    for rad in (R_MIN, R_MAX):
        ax.add_patch(Circle(c, rad, fill=False, ls=':', color='cyan', lw=1))
    ax.set_title('Member segments (colour), other edge pixels (grey)')
    _limits(ax, processed.shape)

    # --- Subplot 2: Vote accumulator ---
    ax = axs[1]
    ia = int(np.argmin(np.abs(ALPHAS_DEG - alpha)))
    ax.imshow(stack[ia], origin='lower', cmap='magma')
    ax.plot(*cand[0], 'x', color='cyan', ms=10, mew=2, label='initial peak')
    ax.plot(*c, '+', color='lime', ms=14, mew=2, label='refined')
    ax.legend(loc='upper right', fontsize=8)
    ax.set_title(f'Vote accumulator at alpha = {ALPHAS_DEG[ia]:+g} deg')
    _limits(ax, processed.shape)

    # --- Subplot 3: Voting rays (lines from R_MIN to R_MAX) ---
    ax = axs[2]
    ax.imshow(processed, cmap='gray', origin='lower', vmin=0, vmax=1)
    
    # Direction vectors rotated by the refined pitch angle alpha
    D = rotate(g.Nc, alpha)
    p_start = g.Ps + R_MIN * D
    p_end = g.Ps + R_MAX * D
    all_rays = np.stack([p_start, p_end], axis=1)  # shape: (N, 2, 2)

    # 1. All other eligible voting rays in the image (background web)
    other_elig = g.eligible & ~member
    if other_elig.any():
        lc_other = LineCollection(all_rays[other_elig], colors='cyan', linewidths=0.4, alpha=0.12)
        ax.add_collection(lc_other)

    # 2. Member voting rays that intersect to define the refined centre
    mem_elig = g.eligible & member
    if mem_elig.any():
        lc_mem = LineCollection(all_rays[mem_elig], colors='orangered', linewidths=0.7, alpha=0.35)
        ax.add_collection(lc_mem)
        # Mark the starting edge pixels for member rays
        ax.scatter(g.Ps[mem_elig, 0], g.Ps[mem_elig, 1], s=2, c='yellow', alpha=0.7, lw=0, zorder=3)

    ax.plot(*c, '+', color='lime', ms=14, mew=2, zorder=4, label='refined centre')
    ax.set_title(f'Voting rays (R={R_MIN:.0f}..{R_MAX:.0f} px): members (red) & all eligible (cyan)')
    _limits(ax, processed.shape)

    fig.savefig(out, dpi=170, bbox_inches='tight')
    plt.close(fig)


