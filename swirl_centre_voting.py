# Arm linking
# -----------------------------------------------------------------------------
def _longest_true_run(mask):
    best, start, best_span = (0, -1), None, -1
    for i, v in enumerate(np.r_[mask, False]):
        if v and start is None:
            start = i
        elif not v and start is not None:
            if i - start > best_span:
                best, best_span = (start, i), i - start
            start = None
    return best


def order_segment(G, g, sel_idx, centre):
    """Order one member segment along its longest path and express it in
    (theta, ln r) about the centre, oriented so that theta increases."""
    nodes = [g.nodes[i] for i in sel_idx]
    sub = G.subgraph(nodes)
    d = nx.single_source_shortest_path_length(sub, nodes[0])
    a = max(d, key=d.get)
    d = nx.single_source_shortest_path_length(sub, a)
    b = max(d, key=d.get)
    idx = np.array([g.index[n] for n in nx.shortest_path(sub, a, b)])
    v = g.Ps[idx] - centre
    theta = np.unwrap(np.arctan2(v[:, 1], v[:, 0]))
    lnr = np.log(np.hypot(v[:, 0], v[:, 1]))
    sm = median_filter(theta, size=5, mode='nearest')
    sgn = 1.0 if sm[-1] >= sm[0] else -1.0
    i0, i1 = _longest_true_run(np.diff(sm) * sgn > -np.radians(1.0))
    keep = slice(i0, i1 + 1)
    idx, theta, lnr = idx[keep], theta[keep], lnr[keep]
    if sgn < 0:
        idx, theta, lnr = idx[::-1], theta[::-1], lnr[::-1]
    return dict(idx=idx, theta=theta, lnr=lnr)


def segment_model(seg, tan_alpha):
    """Local log-spiral model per segment: ln r = ln r_end + b * dtheta."""
    th, lr = seg['theta'], seg['lnr']
    span = float(np.degrees(th[-1] - th[0]))
    b_own = np.polyfit(th, lr, 1)[0] if span >= MIN_SEG_SPAN_DEG and len(th) >= 3 else tan_alpha
    lim = np.tan(np.radians(ALPHAS_DEG.max()))
    b_own = float(np.clip(b_own, -lim, lim))
    w = max(span, 0.0) / (max(span, 0.0) + PITCH_PRIOR_DEG)
    b = w * b_own + (1 - w) * tan_alpha
    win = np.radians(END_WINDOW_DEG)
    s, e = th <= th[0] + win, th >= th[-1] - win
    seg.update(span_deg=span, b_own=b_own, b=b,
               th_start=th[0], th_end=th[-1],
               lr_start=float(np.median(lr[s] - b * (th[s] - th[0]))),
               lr_end=float(np.median(lr[e] - b * (th[e] - th[-1]))))
    return seg


def link_segments(segs):
    """Greedy, lowest-cost linking of compatible log-spiral segments."""
    gap, ovl = np.radians(MAX_GAP_DEG), np.radians(MAX_OVERLAP_DEG)
    cands = []
    for i, A in enumerate(segs):
        for j, B in enumerate(segs):
            if i == j:
                continue
            dth = (B['th_start'] - A['th_end'] + ovl) % (2 * np.pi) - ovl
            if dth > gap or dth + np.radians(B['span_deg']) <= 0:
                continue
            if dth > 0:
                b_mean = 0.5 * (A['b'] + B['b'])
                r_mean = 0.5 * (np.exp(A['lr_end']) + np.exp(B['lr_start']))
                if r_mean * dth * np.sqrt(1 + b_mean ** 2) > MAX_GAP_PX:
                    continue
            mis = 0.5 * (abs(B['lr_start'] - (A['lr_end'] + A['b'] * dth))
                         + abs(A['lr_end'] - (B['lr_start'] - B['b'] * dth)))
            r_here = np.exp(0.5 * (A['lr_end'] + B['lr_start']))
            tol = max(LINK_TOL_LN, LINK_TOL_PX / r_here)
            if mis > tol:
                continue
            dp = abs(np.degrees(np.arctan(A['b']) - np.arctan(B['b'])))
            if dp > MAX_PITCH_DIFF_DEG:
                continue
            cost = mis / tol + max(dth, 0.0) / gap + dp / MAX_PITCH_DIFF_DEG
            cands.append((cost, i, j, float(dth), float(mis)))
    cands.sort()

    head = list(range(len(segs)))
    frame = {i: dict(th=segs[i]['theta'].copy(), lr=segs[i]['lnr'].copy(),
                     tail_end=segs[i]['th_end']) for i in range(len(segs))}

    def self_overlap(th, lr):
        step = 3
        th, lr = th[::step], lr[::step]
        dth_u = np.abs(th[:, None] - th[None, :])
        dth_m = np.abs((th[:, None] - th[None, :] + np.pi) % (2 * np.pi) - np.pi)
        tol = np.maximum(LINK_TOL_LN, SELF_OVERLAP_PX / np.exp(0.5 * (lr[:, None] + lr[None, :])))
        return bool(np.any((dth_u >= np.pi) & (dth_m <= np.radians(3.0))
                           & (np.abs(lr[:, None] - lr[None, :]) <= tol)))

    succ, pred, links = {}, {}, []
    for cost, i, j, dth, mis in cands:
        if i in succ or j in pred:
            continue
        hi, hj = head[i], head[j]
        if hi == hj:
            continue
        fa, fb = frame[hi], frame[hj]
        shift = fa['tail_end'] + dth - segs[hj]['th_start']
        th = np.r_[fa['th'], fb['th'] + shift]
        lr = np.r_[fa['lr'], fb['lr']]
        if self_overlap(th, lr):
            continue
        succ[i], pred[j] = j, i
        frame[hi] = dict(th=th, lr=lr, tail_end=fb['tail_end'] + shift)
        del frame[hj]
        for s in range(len(segs)):
            if head[s] == hj:
                head[s] = hi
        links.append(dict(a=i, b=j, dtheta=dth, mismatch_ln=mis, cost=cost))
    return succ, links


def _model_xy(centre, theta, lnr):
    r = np.exp(lnr)
    return np.column_stack([centre[0] + r * np.cos(theta), centre[1] + r * np.sin(theta)])


def _clip_extension(centre, theta, lnr, valid):
    """Keep the extension until it leaves [R_MIN, R_MAX] or the valid region."""
    xy = _model_xy(centre, theta, lnr)
    r = np.exp(lnr)
    xi, yi = np.rint(xy[:, 0]).astype(int), np.rint(xy[:, 1]).astype(int)
    inside = ((r >= R_MIN) & (r <= R_MAX) & (xi >= 0) & (yi >= 0)
              & (xi < valid.shape[1]) & (yi < valid.shape[0]))
    inside[inside] &= valid[yi[inside], xi[inside]]
    n = len(inside) if inside.all() else int(np.argmin(inside))
    return theta[:n], lnr[:n]


def build_arms(G, g, res, valid):
    """Order, model, link, and assemble member segments into arm chains."""
    centre, alpha, labels = res['centre'], res['alpha'], res['labels']
    tan_a = np.tan(np.radians(alpha))
    segs = []
    for k in np.unique(labels[labels >= 0]):
        seg = order_segment(G, g, np.nonzero(labels == k)[0], centre)
        if len(seg['idx']) >= 3:
            seg['label'] = int(k)
            segs.append(segment_model(seg, tan_a))
    succ, links = link_segments(segs)
    dth_of = {(l['a'], l['b']): l['dtheta'] for l in links}
    has_pred = set(succ.values())
    step = np.radians(1.0)
    chains = []
    for start in [i for i in range(len(segs)) if i not in has_pred]:
        order, i = [start], start
        while i in succ:
            i = succ[i]
            order.append(i)
        pieces, shift, data_th, data_lr = [], 0.0, [], []
        for n, i in enumerate(order):
            s = segs[i]
            if n > 0:
                prev = segs[order[n - 1]]
                dth = dth_of[(order[n - 1], i)]
                end_prev = prev['th_end'] + shift
                shift = end_prev + dth - s['th_start']
                if dth > 0:
                    th = np.linspace(end_prev, end_prev + dth, max(int(dth / step), 2))
                    lr = np.interp(th, [th[0], th[-1]], [prev['lr_end'], s['lr_start']])
                    pieces.append(('bridge', th, lr))
            pieces.append(('data', s['theta'] + shift, s['lnr'], s['idx']))
            data_th.append(s['theta'] + shift)
            data_lr.append(s['lnr'])
        first, last = segs[order[0]], segs[order[-1]]
        ext = np.arange(step, np.radians(EXTEND_DEG) + step / 2, step)
        th_b = first['th_start'] - ext
        th_b, lr_b = _clip_extension(centre, th_b, first['lr_start'] - first['b'] * ext[:len(th_b)], valid)
        th_f = last['th_end'] + shift + ext
        th_f, lr_f = _clip_extension(centre, th_f, last['lr_end'] + last['b'] * ext, valid)
        data_th, data_lr = np.concatenate(data_th), np.concatenate(data_lr)
        coef = np.polyfit(data_th, data_lr, 1) if np.ptp(data_th) > np.radians(MIN_SEG_SPAN_DEG) else (tan_a, 0.0)
        total = np.degrees(data_th.max() - data_th.min())
        bridged = sum(np.degrees(p[1][-1] - p[1][0]) for p in pieces if p[0] == 'bridge')
        rr = np.exp(data_lr)
        chains.append(dict(segments=[segs[i]['label'] for i in order], pieces=pieces,
                           ext_back=(th_b, lr_b), ext_fwd=(th_f, lr_f),
                           n_segments=len(order), winding_deg=float(total),
                           turns=float(total / 360.0), bridged_fraction=float(bridged / max(total, 1e-9)),
                           pitch_deg=float(np.degrees(np.arctan(coef[0]))),
                           rms_lnr=float(np.std(data_lr - np.polyval(coef, data_th))),
                           r_min=float(rr.min()), r_max=float(rr.max()),
                           theta_start_deg=float(np.degrees(data_th.min()))))
    chains.sort(key=lambda c: c['winding_deg'], reverse=True)
    return chains, segs, links


def plot_arms(k, processed, g, res, chains, out):
    c = res['centre']
    fig = plt.figure(figsize=(20, 7), constrained_layout=True)
    ax0 = fig.add_subplot(1, 3, 1)
    ax1 = fig.add_subplot(1, 3, 2, projection='polar')
    ax2 = fig.add_subplot(1, 3, 3)
    fig.suptitle(f'Centre {k}: arms from linked segments (solid = data, dashed = bridged gap, '
                 f'dotted = extrapolation); centre pitch {res["alpha"]:+.1f} deg',
                 fontsize=13, weight='bold')
    ax0.imshow(processed, cmap='gray', origin='lower', vmin=0, vmax=1)
    cmap = plt.get_cmap('tab10')
    multi = [ch for ch in chains if ch['n_segments'] > 1]
    for ch in chains:
        is_arm = ch['n_segments'] > 1
        col = cmap(multi.index(ch) % 10) if is_arm else '0.6'
        lw = 2.2 if is_arm else 1.0
        label = (f"arm {multi.index(ch)}: {ch['n_segments']} segs, {ch['winding_deg']:.0f} deg, "
                 f"pitch {ch['pitch_deg']:+.0f}, bridged {ch['bridged_fraction']:.0%}") if is_arm else None
        for p in ch['pieces']:
            ls = '-' if p[0] == 'data' else '--'
            xy = g.Ps[p[3]] if p[0] == 'data' else _model_xy(c, p[1], p[2])
            ax0.plot(xy[:, 0], xy[:, 1], ls, color=col, lw=lw)
            ax1.plot(p[1], np.exp(p[2]), ls, color=col, lw=lw)
            ax2.plot(np.degrees(p[1]), p[2], ls, color=col, lw=lw,
                     label=label if (p is ch['pieces'][0]) else None)
        for th, lr in (ch['ext_back'], ch['ext_fwd']):
            if len(th) and (is_arm or EXTEND_SINGLES):
                xy = _model_xy(c, th, lr)
                ax0.plot(xy[:, 0], xy[:, 1], ':', color=col, lw=lw * 0.8)
                ax1.plot(th, np.exp(lr), ':', color=col, lw=lw * 0.8)
                ax2.plot(np.degrees(th), lr, ':', color=col, lw=lw * 0.8)
    ax0.plot(*c, '+', color='red', ms=14, mew=2)
    _limits(ax0, processed.shape)
    ax0.set_title('Image')
    ax1.set_rmax(R_MAX)
    ax1.set_title('Polar view about the centre (r in px)')
    ax2.set(xlabel='unwrapped theta [deg] (CCW)', ylabel='ln r',
            title='Log-polar: a log-spiral arm is a straight line')
    if multi:
        ax2.legend(fontsize=8, loc='best')
    fig.savefig(out, dpi=170, bbox_inches='tight')
    plt.close(fig)


