def pixel_geometry(G):
    """Smoothed position, tangent, concave normal, curvature, vote weight."""
    g = Geometry()
    g.nodes = list(G.nodes)
    N = len(g.nodes)
    index = {node: i for i, node in enumerate(g.nodes)}
    P = np.array([tracker.xy(n) for n in g.nodes]) if N else np.zeros((0, 2))
    cutoff = max(SMOOTH_HOPS, TANGENT_HOPS, CURV_HOPS, MEMBER_HOPS)

    hoods = []
    rows, cols = [], []
    for i, node in enumerate(g.nodes):
        d = nx.single_source_shortest_path_length(G, node, cutoff=cutoff)
        idx = np.fromiter((index[m] for m in d), int, len(d))
        hop = np.fromiter(d.values(), int, len(d))
        hoods.append((idx, hop))
        sel = idx[hop <= MEMBER_HOPS]
        rows.extend([i] * len(sel))
        cols.extend(sel.tolist())

    Ps = np.array([P[idx[hop <= SMOOTH_HOPS]].mean(0) for idx, hop in hoods]) if N else P
    T = np.zeros((N, 2))
    Nc = np.zeros((N, 2))
    kappa = np.zeros(N)
    coh = np.zeros(N)
    for i, (idx, hop) in enumerate(hoods):
        pts = Ps[idx[hop <= TANGENT_HOPS]]
        if len(pts) < 4:
            continue
        q = pts - pts.mean(0)
        vals, vecs = np.linalg.eigh(q.T @ q)
        t = vecs[:, 1]
        coh[i] = (vals[1] - vals[0]) / (vals[1] + vals[0] + 1e-12)
        nrm = np.array([-t[1], t[0]])
        rel = Ps[idx[hop <= CURV_HOPS]] - Ps[i]
        xx, yy = rel @ t, rel @ nrm
        k = 0.0
        if len(xx) >= 5 and np.ptp(xx) >= 3:
            try:
                a, b, _ = np.polyfit(xx, yy, 2)
                k = 2 * a / (1 + b * b) ** 1.5
            except Exception:
                k = 0.0
        T[i] = t
        kappa[i] = abs(k)
        Nc[i] = nrm if k >= 0 else -nrm   # concave side

    weight = np.where(coh >= MIN_COHERENCE, coh * kappa / (kappa + KAPPA_SOFT), 0.0)
    g.P, g.Ps, g.T, g.Nc = P, Ps, T, Nc
    g.kappa, g.coherence, g.weight = kappa, coh, weight
    g.eligible = weight > 0
    g.index = index
    g.component = np.zeros(N, int)
    for k, comp in enumerate(nx.connected_components(G)):
        g.component[[index[n] for n in comp]] = k
    g.hood = sparse.csr_matrix((np.ones(len(rows)), (rows, cols)), shape=(N, N))
    return g


def rotate(V, deg):
    c, s = np.cos(np.radians(deg)), np.sin(np.radians(deg))
    return np.column_stack([c * V[:, 0] - s * V[:, 1], s * V[:, 0] + c * V[:, 1]])


def signed_angle(a, b):
    """Signed angle (deg) from vectors a to b, counter-clockwise positive."""
    cross = a[:, 0] * b[:, 1] - a[:, 1] * b[:, 0]
    return np.degrees(np.arctan2(cross, (a * b).sum(1)))


def wrap(deg):
    return (deg + 180.0) % 360.0 - 180.0


